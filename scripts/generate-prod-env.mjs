/**
 * Generates src/environments/environment.prod.generated.ts from env vars (npm run build).
 * Reads a root .env in the frontend directory if present.
 *
 * Variables:
 *   NG_APP_API_URL — optional full https://…/api, or /api (same-origin proxy).
 *   ENABLE_LOCAL_SUPER_ADMIN — true to allow Super Admin login without API.
 *   SUPER_ADMIN_EMAIL / SUPER_ADMIN_PASSWORD — only used if ENABLE_LOCAL_SUPER_ADMIN=true.
 *
 * Direct `ng build` without npm will skip this script — use `npm run build`.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const envFile = path.join(root, '.env');

function loadDotEnv() {
  if (!fs.existsSync(envFile)) return;
  const text = fs.readFileSync(envFile, 'utf8');
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    if (process.env[key] === undefined) {
      process.env[key] = val;
    }
  }
}

loadDotEnv();

function normalizeApiUrl(raw) {
  let u = (raw ?? '').trim();
  if (!u) return '/api';
  u = u.replace(/\/$/, '');
  if (u.startsWith('http://') || u.startsWith('https://')) {
    if (!/\/api$/i.test(u)) return `${u}/api`;
    return u;
  }
  if (u.startsWith('/')) {
    if (u === '/api' || u.startsWith('/api/')) return u;
    return '/api';
  }
  return '/api';
}

const apiUrl = normalizeApiUrl(process.env.NG_APP_API_URL);
const enableLocalSuperAdminLogin = process.env.ENABLE_LOCAL_SUPER_ADMIN === 'true';
const superAdminEmail = process.env.SUPER_ADMIN_EMAIL ?? '';
const superAdminPassword = process.env.SUPER_ADMIN_PASSWORD ?? '';

const out = `/* Generated by scripts/generate-prod-env.mjs — do not edit */
import type { AppEnvironment } from './environment.types';

export const environment: AppEnvironment = {
  production: true,
  apiUrl: ${JSON.stringify(apiUrl)},
  enableLocalSuperAdminLogin: ${enableLocalSuperAdminLogin},
  superAdminEmail: ${JSON.stringify(enableLocalSuperAdminLogin ? superAdminEmail : '')},
  superAdminPassword: ${JSON.stringify(enableLocalSuperAdminLogin ? superAdminPassword : '')},
};
`;

const target = path.join(root, 'src/environments/environment.prod.generated.ts');
fs.writeFileSync(target, out, 'utf8');
console.log('Wrote', path.relative(root, target));
console.log('  apiUrl:', apiUrl);
console.log('  enableLocalSuperAdminLogin:', enableLocalSuperAdminLogin);
