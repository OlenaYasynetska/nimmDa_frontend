/**
 * Generates src/environments/environment.prod.generated.ts from env vars (npm run build).
 * Reads a root .env in the frontend directory if present.
 *
 * Variables:
 *   NG_APP_API_URL — optional full https://…/api, or /api (same-origin proxy).
 *   NG_APP_GA_MEASUREMENT_ID — optional GA4 stream ID (G-XXXXXXXXXX).
 *   NG_APP_ADSENSE_CLIENT — AdSense publisher id (ca-pub-…). Defaults to the NimmDa account.
 *   NG_APP_ADSENSE_SLOT — optional display-ad slot id. Empty keeps the visible ad unit off.
 *
 * Flags:
 *   --mobile       use https://api.nimmda.org/api when NG_APP_API_URL is relative
 *   --api <url>    override NG_APP_API_URL for this run
 *
 * Direct `ng build` without npm will skip this script — use `npm run build`.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const envFile = path.join(root, '.env');

function loadDotEnv() {
  if (!fs.existsSync(envFile)) return;
  const text = fs.readFileSync(envFile, 'utf8');
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    if (process.env[key] === undefined) {
      process.env[key] = val;
    }
  }
}

function readArg(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) return undefined;
  const value = process.argv[index + 1];
  if (!value || value.startsWith('--')) return undefined;
  return value;
}

loadDotEnv();

const apiOverride = readArg('--api');
if (apiOverride) {
  process.env.NG_APP_API_URL = apiOverride;
}

function normalizeApiUrl(raw) {
  let u = (raw ?? '').trim();
  if (!u) return '/api';
  u = u.replace(/\/$/, '');
  if (u.startsWith('http://') || u.startsWith('https://')) {
    if (!/\/api$/i.test(u)) return `${u}/api`;
    return u;
  }
  if (u.startsWith('/')) {
    if (u === '/api' || u.startsWith('/api/')) return u;
    return '/api';
  }
  return '/api';
}

function readAdSenseClient(raw) {
  const id = (raw ?? '').trim();
  if (!id) return '';
  if (!/^ca-pub-\d+$/.test(id)) {
    console.error('');
    console.error('NG_APP_ADSENSE_CLIENT must look like ca-pub-1234567890123.');
    console.error('');
    process.exit(1);
  }
  return id;
}

function readAdSenseSlot(raw) {
  const id = (raw ?? '').trim();
  if (!id) return '';
  if (!/^\d{6,}$/.test(id)) {
    console.error('');
    console.error('NG_APP_ADSENSE_SLOT must be the numeric slot id from AdSense.');
    console.error('');
    process.exit(1);
  }
  return id;
}

function readMeasurementId(raw) {
  const id = (raw ?? '').trim();
  if (!id) return '';
  if (!/^G-[A-Z0-9]+$/.test(id)) {
    console.error('');
    console.error('NG_APP_GA_MEASUREMENT_ID must look like G-XXXXXXXXXX.');
    console.error('Copy it from Google Analytics → Admin → Data streams.');
    console.error('');
    process.exit(1);
  }
  return id;
}

const mobile = process.argv.includes('--mobile');
const PRODUCTION_API = 'https://api.nimmda.org/api';
let apiUrl = normalizeApiUrl(process.env.NG_APP_API_URL);
if (mobile && !/^https?:\/\//i.test(apiUrl)) {
  apiUrl = PRODUCTION_API;
}
const gaMeasurementId = readMeasurementId(
  process.env.NG_APP_GA_MEASUREMENT_ID || 'G-JL2HHG2SKY'
);
const adsenseClient = readAdSenseClient(
  process.env.NG_APP_ADSENSE_CLIENT || 'ca-pub-7335564704542106'
);
const adsenseSlot = readAdSenseSlot(process.env.NG_APP_ADSENSE_SLOT);

const out = `/* Generated by scripts/generate-prod-env.mjs — do not edit */
import type { AppEnvironment } from './environment.types';

export const environment: AppEnvironment = {
  production: true,
  apiUrl: ${JSON.stringify(apiUrl)},
  gaMeasurementId: ${JSON.stringify(gaMeasurementId)},
  adsenseClient: ${JSON.stringify(adsenseClient)},
  adsenseSlot: ${JSON.stringify(adsenseSlot)},
};
`;

const target = path.join(root, 'src/environments/environment.prod.generated.ts');
fs.writeFileSync(target, out, 'utf8');
console.log('Wrote', path.relative(root, target));
console.log('  apiUrl:', apiUrl);
console.log('  gaMeasurementId:', gaMeasurementId || '(off)');
console.log('  adsense:', adsenseClient && adsenseSlot ? 'on' : '(off)');
